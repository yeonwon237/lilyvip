import assert from 'node:assert/strict';
import { setLocale } from '../src/i18n';
setLocale('vi');
import { PRODUCT_PLANS } from '../src/config/plans';
import { resolveInitialPage } from '../src/config/navigation';
import { canUseFeature, getLibraryLimits, getPlanName, isLegacyPlan } from '../src/config/features';

assert.equal(resolveInitialPage('', false), 'landing');
assert.equal(resolveInitialPage('', true), 'dashboard');
assert.equal(resolveInitialPage('?welcome=1', true), 'landing');
assert.equal(resolveInitialPage('?about=1', true), 'about');
assert.equal(resolveInitialPage('?legal=1', true), 'legal');
assert.equal(resolveInitialPage('?novel=abc', false), 'add-book');
assert.equal(resolveInitialPage('?connect=lilyhub', true), 'login');
assert.deepEqual(PRODUCT_PLANS.map(plan => plan.name), ['MIỄN PHÍ', 'MY01', 'MY02']);
assert.equal(PRODUCT_PLANS.filter(plan => plan.recommended).length, 1);
assert.equal(PRODUCT_PLANS.find(plan => plan.name === 'MY01')?.price, '239.000đ / năm');
assert.equal(PRODUCT_PLANS.find(plan => plan.name === 'MY02')?.price, '399.000đ / năm');
assert.equal(PRODUCT_PLANS.length, 3);
assert.equal(PRODUCT_PLANS.some(plan => plan.benefits.some(benefit => /mọi nguồn/i.test(benefit))), false);
assert.equal(canUseFeature('backup', 'free'), false);
assert.equal(canUseFeature('backup', 'audio'), false);
assert.equal(canUseFeature('backup', 'vip1'), true);
assert.equal(canUseFeature('backup', 'vip2'), true);
console.log('Business readiness: entry routing and canonical product plans passed');

setLocale('en');
assert.equal(PRODUCT_PLANS[0].name, 'FREE');
assert.equal(PRODUCT_PLANS.find(plan => plan.tier === 'vip1')?.price, '239,000₫ / year');
setLocale('vi');
assert.equal(PRODUCT_PLANS[0].name, 'MIỄN PHÍ');

const future = new Date(Date.now() + 86400000).toISOString();
const past = new Date(Date.now() - 86400000).toISOString();
const legacy = { subscriptionPlanVersion: 'legacy' as const, subscriptionEndsAt: future };
assert.equal(getLibraryLimits('vip1', legacy).total, 50);
assert.equal(getLibraryLimits('vip2', legacy).total, 100);
assert.equal(getPlanName('vip1', legacy), 'MY50');
assert.equal(getPlanName('vip2', legacy), 'MY100');
assert.equal(getLibraryLimits('vip2', { ...legacy, subscriptionEndsAt: past }).total, 15);
const queued = { subscriptionPlanVersion: '2026-10' as const, subscriptionEndsAt: future, subscriptionLegacyUntil: future };
assert.equal(getLibraryLimits('vip2', queued).total, 100);
assert.equal(getLibraryLimits('vip2', { ...queued, subscriptionLegacyUntil: past }).total, Infinity);
assert.equal(getLibraryLimits('vip1').total, 100);
assert.equal(getLibraryLimits('free').total, 15);
assert.equal(getPlanName('vip2'), 'MY02');
assert.equal(isLegacyPlan(queued, Date.parse(future)), false);
console.log('Plan entitlements: legacy, early renewal, expiration, pooled free limits and unlimited MY02 passed');
